package usecase

// 入力の大きさの上限。**超えたら縮小も切り捨てもせず弾く**
// （画像は ADR 0018、シーンは ADR 0038）。
//
// 黙って縮めたり捨てたりすると、渡したつもりの情報が入力から消えたことに
// 開発者が気づけない。中核思想 3 の「自動で判断せず、状態を見せて選ばせる」に
// 反する。
//
// **上限を持つのはサーバーだけである。** フロントは画像の書き出し解像度を
// 抑えるが、バイト数の判定は持たない。両方に持たせると、片方だけ変えたときに
// 「フロントは通すがサーバーが弾く」がどちらの言い分か分からなくなる。
//
// **1 箇所に並べてあるのは、片方だけ動かすと筋が通らなくなるため。** 解釈に
// 渡す画像に上限があるのに保存が無制限だと、同じボードが「保存はできるが
// 解釈はできない」ではなく「保存できるが際限なく重くなる」に落ちる。
//
// 呼び出し側がリクエストボディの大きさを見積もれるよう公開している。
const (
	// MaxImageBytes は画像 1 枚のバイト数の上限。
	MaxImageBytes = 4 << 20
	// MaxImages は解釈 1 回に渡せる画像の枚数の上限。
	//
	// 注釈は 1 つの frame なので、写すべき範囲も 1 つ。
	MaxImages = 1

	// MaxSceneBytes は保存できるシーン JSON のバイト数の上限（ADR 0038）。
	//
	// **効いてくるのはキャンバスに貼った画像である。** シーンは
	// `serializeAsJSON` が `getFiles()` ごと直列化するので、貼った画像が
	// base64（元の 4/3）でシーンに乗る。図形とテキストだけのボードがこの
	// 大きさに届くことはない。
	//
	// 8 MiB にしてあるのは、**解釈に渡せる画像 1 枚（MaxImageBytes = 4 MiB）を
	// base64 で載せてなお余る**ところに置くため。それより小さいと、解釈できる
	// 図を描いたボードが保存できないという逆立ちが起きる。
	//
	// 上限を設けること自体の理由は「壊れ方が読めるようにする」。無制限だと
	// 破綻の出方が「保存に失敗する」ではなく「保存・一覧・解釈がだんだん
	// 重くなる」になり、原因に辿り着けない。
	MaxSceneBytes = 8 << 20

	// MaxDiagramTurns は図のドラフトを 1 つ作るまでに重ねられるやりとりの数。
	//
	// **会話はサーバーに残らない**（ADR 0041）。毎回まるごと送られてくるので、
	// 伸びたぶんはそのまま 1 回の呼び出しのトークンに乗る。上限が無いと、
	// 直らない出力に「もう一度」を繰り返すだけで際限なく大きくなる。
	//
	// 上限に当たったら**黙って古いやりとりを捨てない。** 捨てると、直前まで
	// 積み上げた指示のどれが効いているのかが分からなくなる。会話をやり直すか
	// どうかは開発者が決める（中核思想 3）。
	MaxDiagramTurns = 10

	// MaxDiagramChatBytes は 1 回の生成に送れる会話全体のバイト数の上限。
	//
	// **回数だけでは足りない。** 1 通に長文を貼れば、往復 1 回で同じだけ
	// 積み上がる。数えるのは今回のプロンプトと過去のやりとりの合計で、
	// 送られてきたものそのもの。
	MaxDiagramChatBytes = 32 << 10
)

// SceneExceedsLimit はシーンが MaxSceneBytes を超えていて、このままでは
// 保存できないことを返す（issue #103）。
//
// **比較はここ 1 箇所に閉じる。** validateScene の 413 判定と、
// BoardDetail.sceneOverLimit（保存済みシーンが上限を超えたまま残っていないか
// を開いた時点で示す）が同じ関数を呼ぶ。2 箇所で `len(scene) > MaxSceneBytes`
// を書くと、上限を動かしたときに片方だけ直し忘れる。
func SceneExceedsLimit(scene string) bool {
	return len(scene) > MaxSceneBytes
}
