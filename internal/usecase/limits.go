package usecase

// 入力の大きさの上限。**超えたら縮小も切り捨てもせず弾く**
// （解釈に渡す画像は ADR 0018、シーンは ADR 0038、貼った画像は ADR 0074）。
//
// 黙って縮めたり捨てたりすると、渡したつもりの情報が入力から消えたことに
// 開発者が気づけない。中核思想 3 の「自動で判断せず、状態を見せて選ばせる」に
// 反する。
//
// **上限を持つのはサーバーだけである。** フロントは画像の書き出し解像度を
// 抑えるが、バイト数の判定は持たない。両方に持たせると、片方だけ変えたときに
// 「フロントは通すがサーバーが弾く」がどちらの言い分か分からなくなる。
//
// **1 箇所に並べてあるのは、片方だけ動かすと筋が通らなくなるため。** 解釈に
// 渡す画像に上限があるのに保存が無制限だと、同じボードが「保存はできるが
// 解釈はできない」ではなく「保存できるが際限なく重くなる」に落ちる。
//
// 呼び出し側がリクエストボディの大きさを見積もれるよう公開している。
const (
	// MaxImageBytes は解釈に渡す画像 1 枚のバイト数の上限。キャンバスに
	// 貼った画像の上限（MaxBoardFileBytes）とは別のもの。
	MaxImageBytes = 4 << 20
	// MaxImages は解釈 1 回に渡せる画像の枚数の上限。
	//
	// 注釈は 1 つの frame なので、写すべき範囲も 1 つ。
	MaxImages = 1

	// MaxSceneBytes は保存できるシーン JSON のバイト数の上限（ADR 0038）。
	//
	// **貼った画像はここに数えない。** 画像はシーンとは別に持ち、合計を
	// MaxBoardFileBytes で縛る（ADR 0074）。図形とテキストだけのシーンが
	// この大きさに届くことはまずない。
	//
	// 値は画像を分ける前のまま据え置いた。画像を分けた以上、もとの根拠
	// （解釈に渡せる画像 1 枚を base64 で載せてなお余る）は効いていないが、
	// 下げても得るものが無い。上限を設けること自体の理由は変わらず「壊れ方が
	// 読めるようにする」。無制限だと破綻の出方が「保存に失敗する」ではなく
	// 「保存・一覧・解釈がだんだん重くなる」になり、原因に辿り着けない。
	MaxSceneBytes = 8 << 20

	// MaxBoardFileBytes はボード 1 枚が持てる、貼った画像の合計バイト数の上限
	// （ADR 0074）。数えるのは保存したあとに残る画像だけで、外した画像は
	// 数えない（保存で消える）。
	//
	// **1 枚ごとの上限は置かない。** 1 枚が合計を超えることはできず、貼る時点
	// では Excalidraw が 1 枚 4 MiB（base64 で約 5.3 MiB）を超える画像を拒む。
	// 32 MiB はその最大の画像でも 5 枚、数百 KB の画面写しなら数十枚が載る
	// ところに置いた。ボードを開くときの応答はこれに比例して大きくなる。
	//
	// **MaxSceneBytes（8 MiB）より小さくしない。** 分ける前は画像込みで 8 MiB
	// まで保存できていた。それより小さいと、移行しただけで保存し直せない
	// ボードが出る。
	MaxBoardFileBytes = 32 << 20

	// MaxDiagramTurns は図のドラフトを 1 つ作るまでに重ねられるやりとりの数。
	//
	// **会話はサーバーに残らない**（ADR 0041）。毎回まるごと送られてくるので、
	// 伸びたぶんはそのまま 1 回の呼び出しのトークンに乗る。上限が無いと、
	// 直らない出力に「もう一度」を繰り返すだけで際限なく大きくなる。
	//
	// 上限に当たったら**黙って古いやりとりを捨てない。** 捨てると、直前まで
	// 積み上げた指示のどれが効いているのかが分からなくなる。会話をやり直すか
	// どうかは開発者が決める（中核思想 3）。
	MaxDiagramTurns = 10

	// MaxDiagramChatBytes は 1 回の生成に送れる会話全体のバイト数の上限。
	//
	// **回数だけでは足りない。** 1 通に長文を貼れば、往復 1 回で同じだけ
	// 積み上がる。数えるのは今回のプロンプトと過去のやりとりの合計で、
	// 送られてきたものそのもの。
	MaxDiagramChatBytes = 32 << 10
)

// SceneExceedsLimit はシーンが MaxSceneBytes を超えていて、このままでは
// 保存できないことを返す（issue #103）。
//
// **比較はここ 1 箇所に閉じる。** validateScene の 413 判定と、
// BoardDetail.sceneOverLimit（保存済みシーンが上限を超えたまま残っていないか
// を開いた時点で示す）が同じ関数を呼ぶ。2 箇所で `len(scene) > MaxSceneBytes`
// を書くと、上限を動かしたときに片方だけ直し忘れる。
func SceneExceedsLimit(scene string) bool {
	return len(scene) > MaxSceneBytes
}

// FilesExceedLimit は貼った画像の合計が MaxBoardFileBytes を超えていて、
// このままでは保存できないことを返す（ADR 0074）。
//
// SceneExceedsLimit と同じく、保存の 413 判定と BoardDetail.sceneOverLimit が
// これを呼ぶ。
func FilesExceedLimit(total int64) bool {
	return total > MaxBoardFileBytes
}

// boardExceedsLimit は保存済みのボードが、このままでは保存し直せないことを返す。
//
// シーンと画像のどちらが超えていても、利用者の打ち手は「貼った画像を減らす」
// か「描いたものを減らす」で、保存できないことに変わりはない。境界には 1 つの
// 真偽値で出す（ADR 0048 / 0074）。
func boardExceedsLimit(scene string, fileBytes int64) bool {
	return SceneExceedsLimit(scene) || FilesExceedLimit(fileBytes)
}
