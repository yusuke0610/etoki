-- ログイン後の戻り先を state と一緒に持つ（ADR 0056、#149）。
--
-- ボードを URL で開けるようにすると、セッションが切れて入り直した人は
-- 作業していたボードを探し直すことになる。戻り先を持ち回る先は 2 つあり、
-- 認可のコールバックの URL に載せるか、サーバーが state と一緒に持つか。
-- **後者にした。** URL に載せると、戻ってきた URL の中身が戻り先を決める
-- ことになり、オープンリダイレクトを塞ぐ責任が毎回の照合に移る。state は
-- すでにサーバー発行・単回使用・期限つきで、同じ寿命のものを増やすだけで済む。
--
-- 既存の行は空文字になる。空文字は「戻り先を知らない」で、これまでどおり
-- "/" に戻す。NULL にしないのは、「まだ列が無かった頃」と「戻り先を指定
-- しなかった」を区別する必要が無いため。
--
-- 子テーブルから参照されていないので、テーブルの作り直しは要らない
-- （ADR 0049 の印も不要）。
ALTER TABLE oauth_states ADD COLUMN return_to TEXT NOT NULL DEFAULT '';
